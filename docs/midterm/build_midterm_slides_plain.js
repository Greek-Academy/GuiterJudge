const td = (t, o = {}) => ({ text: t, options: Object.assign({ color: INK, fontFace: FONT, fontSize: 12, valign: 'middle', align: 'left', border: [{ type: 'none' }, { type: 'none' }, { type: 'solid', color: RULE, pt: 0.75 }, { type: 'none' }] }, o) });
function table(s, rows, colW, y, rowH = 0.45) {
  s.addTable(rows, { x: 0.6, y, w: 8.8, colW, rowH, margin: 0.05 });
}

